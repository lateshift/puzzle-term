//! CSI negotiation trace with the active screen before each sequence.
//!
//! Keyboard mode is a property of the screen selected when CSI is parsed.
//! Nvim enters alternate screen before pushing kitty flags, then queries
//! them there. Logging only final flags would hide a wrong primary/alternate
//! transition. This trace keeps the full raw output and replays it through
//! a small terminal model to annotate each matching CSI with that screen.
//!
//! The diagnostic records bytes in hexadecimal so an ESC prefix, C0 byte
//! or unexpected parameter separator is unambiguous in a text artifact.
//! It does not normalize kitty's push, pop, set or query forms: the exact
//! wire sequence is the evidence. A future nvim version can change its
//! requested flags without the trace quietly rewriting the request.
//!
//! The scan is separate from Session's real parser. Session may pause at
//! its feed time budget while raw PTY bytes already sit in this buffer.
//! The key artifact therefore also records the flags sampled at key time;
//! a raw trace alone cannot prove the state Session used for encoding.
//!
//! CSI final bytes occupy 0x40..0x7e. Finding that byte bounds each
//! candidate sequence before matching its prefix, so parameters such as
//! `?1049` cannot be confused with printable text that follows the final.
//! The stream is generated by the fixed local nvim child and capped by the
//! caller; malformed or incomplete CSI suffixes simply advance one byte.
use puzzle_term::vt::Terminal;
/// Renders control bytes explicitly for review and exact byte assertions.
/// A plain string would make a legacy Ctrl+D invisible and render an ESC
/// prefix differently across log viewers and terminals.
pub(super) fn escaped(bytes: &[u8]) -> String {
    bytes
        .iter()
        .map(|byte| format!("{byte:02x}"))
        .collect::<Vec<_>>()
        .join(" ")
}

/// Finds input-mode CSI sequences and annotates the screen at their arrival.
/// The replay applies every sequence, including unlogged cursor and color
/// controls, because a screen switch must take effect before later kitty
/// pushes are annotated. Only the selected input-mode families are emitted.
pub(super) fn mode_trace(bytes: &[u8]) -> String {
    let mut screen = Terminal::new(100, 30, 0, 0);
    let mut result = String::new();
    let mut at = 0;
    while at < bytes.len() {
        // CSI may be fragmented across PTY reads; scanning the joined raw
        // stream avoids falsely treating one fragment as plain text.
        if bytes[at..].starts_with(b"\x1b[")
            && let Some(end) = bytes[at + 2..]
                .iter()
                .position(|byte| (0x40..=0x7e).contains(byte))
        {
            let end = at + 3 + end;
            let sequence = &bytes[at..end];
            // Report the old screen for ?1049h/l: the switch occurs
            // when the sequence is applied immediately below.
            if is_input_mode(sequence) {
                result.push_str(&format!(
                    "screen={:?} flags={} bytes={}\n",
                    screen.active,
                    screen.kitty_keys.flags(screen.active),
                    escaped(sequence)
                ));
            }
            screen.advance(sequence);
            at = end;
            continue;
        }
        // Parser state also sees non-CSI bytes; ESC D and OSC sequences may
        // affect VT state even though this trace does not print them.
        screen.advance(&bytes[at..at + 1]);
        at += 1;
    }
    result
}

/// Includes every negotiation family relevant to Ctrl+D encoding.
/// DECCKM and 1049 use exact parameters. Prefix matching `?1` would also
/// capture unrelated mouse modes 1002/1006 and obscure the useful trace.
fn is_input_mode(bytes: &[u8]) -> bool {
    let body = &bytes[2..];
    (body.starts_with(b">")
        || body.starts_with(b"<")
        || body.starts_with(b"=")
        || body.starts_with(b"?"))
        && (body.ends_with(b"u")
            || body.starts_with(b">4;") && body.ends_with(b"m")
            || body == b"?1h"
            || body == b"?1l"
            || body == b"?1049h"
            || body == b"?1049l")
}
