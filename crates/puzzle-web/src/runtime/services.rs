//! Core services retain only Send plain data, never a browser closure (§4.3).
//!
//! Queue draining transfers ownership to the host after pump/feed; callback
//! reentrancy can then write or dispose without a RefCell borrow spanning JS.
use puzzle_term::platform::{PtySize, Transport, TransportEffect, WakeRequests, Waker};
// The deferred clipboard queue preserves policy-approved writes until the
// platform can perform them; a read requests a later native paste event.
use std::collections::VecDeque;
use web_time::Instant;

/// Ordered writes, resizes and close operations are flushed outside Session.
#[derive(Default)]
pub(super) struct DeferredTransport(VecDeque<TransportEffect>);
/// Browser I/O is represented as typed ownership transfers (R9).
impl Transport for DeferredTransport {
    /// Input and parser replies share this FIFO, preserving application order.
    fn write(&mut self, bytes: &[u8]) -> Result<(), String> {
        self.0.push_back(TransportEffect::Write(bytes.to_vec()));
        Ok(())
    }
    /// Browser callback receipt is distinct from actual bridge writer completion.
    fn deferred_replies(&self) -> bool {
        true
    }
    /// The host's existing flush turn moves ownership without returning credit early.
    fn write_reply(
        &mut self,
        reply: puzzle_term::platform::reply::ReplyWrite,
    ) -> Result<puzzle_term::platform::reply::ReplyDelivery, String> {
        // Transfer payload ownership without pretending a foreign callback consumed it.
        // Socket credit or a host Promise returns the receipt in a later owner turn.
        self.0.push_back(TransportEffect::Reply(reply));
        Ok(puzzle_term::platform::reply::ReplyDelivery::Pending)
    }
    /// A resize cannot leap over a reply already generated by this turn.
    fn resize(&mut self, size: PtySize) -> Result<(), String> {
        self.0.push_back(TransportEffect::Resize(size));
        Ok(())
    }
    /// Closing stays ordered behind final replies and writes.
    fn close(&mut self) -> Result<(), String> {
        self.0.push_back(TransportEffect::Close);
        Ok(())
    }
    /// Taking one effect moves its buffer rather than sharing mutable state.
    fn take_effect(&mut self) -> Option<TransportEffect> {
        self.0.pop_front()
    }
}

/// Damage and earliest timeout coalesce without registering JS timers in core.
#[derive(Default)]
pub(super) struct DeferredWaker(WakeRequests);
/// The eventual rAF host consumes one request record per core turn.
impl Waker for DeferredWaker {
    /// Multiple dirty rows need only one refresh callback.
    fn request_frame(&mut self) {
        self.0.frame = true;
    }
    /// The earliest sync or blink deadline takes precedence.
    fn wake_at(&mut self, at: Instant) {
        self.0.deadline = Some(self.0.deadline.map_or(at, |old| old.min(at)));
    }
    /// Taking clears the record, so an idle terminal schedules no polling.
    fn take_requests(&mut self) -> WakeRequests {
        std::mem::take(&mut self.0)
    }
}

/// A paste shortcut asks the DOM to preserve its native clipboard event.
#[derive(Default)]
pub(super) struct DeferredClipboard(VecDeque<puzzle_term::platform::ClipboardEffect>);
/// Clipboard policy remains in core; actual browser access is deferred.
impl puzzle_term::platform::Clipboard for DeferredClipboard {
    /// Stores only validated text so JS can write it outside the parser.
    fn write_text(&mut self, text: &str) -> Result<(), String> {
        self.0
            .push_back(puzzle_term::platform::ClipboardEffect::Write(text.into()));
        Ok(())
    }
    /// Keep both MIME payloads together until the browser's user gesture writes them.
    fn write_html(&mut self, html: &str, text: &str) -> Result<(), String> {
        // One queue entry keeps rich and plain alternatives atomic at the host.
        // The DOM key callback takes ownership before starting asynchronous JS.
        self.0
            .push_back(puzzle_term::platform::ClipboardEffect::WriteHtml {
                html: html.into(),
                text: text.into(),
            });
        Ok(())
    }
    /// No text is guessed; the later paste event supplies its actual value.
    fn request_text(&mut self) -> Result<Option<String>, String> {
        self.0
            .push_back(puzzle_term::platform::ClipboardEffect::Read);
        Ok(None)
    }
    /// Moves an owned request without an unsafe Send wrapper.
    fn take_effect(&mut self) -> Option<puzzle_term::platform::ClipboardEffect> {
        self.0.pop_front()
    }
}

/// Approved link transactions stay data until the original DOM turn releases Session.
#[derive(Default)]
pub(super) struct DeferredUrl(VecDeque<String>);
/// Opening never invokes foreign JavaScript while the runtime is mutably borrowed.
impl puzzle_term::platform::UrlOpener for DeferredUrl {
    /// Owns the bounded URI after core gesture and scheme policy completed.
    fn open(&mut self, uri: &str) -> Result<(), String> {
        self.0.push_back(uri.into());
        Ok(())
    }
    /// Moves ownership without a callback or retained browser object in core.
    fn take_effect(&mut self) -> Option<String> {
        self.0.pop_front()
    }
}
