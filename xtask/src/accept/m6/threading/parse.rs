//! D-50 replaces D-29 lock acceptance with ownership and publication evidence.
//! Exact named witnesses preserve the fixed-slice control boundary, 100000
//! handoffs and real-PTY DA/CPR order. The shared-lock ceilings were withdrawn
//! explicitly by D-50, so a missing mutex cannot manufacture a zero timing pass.
//! Publication records retain queue delay and paired owner wall/CPU intervals;
//! late counts remain visible without inventing a new request-latency threshold.
//!
//! The Session owner can be descheduled before applying a request or while
//! advancing its models. Those are different intervals: control wait has only a
//! wall clock, while application-to-publication has both clocks from the same
//! thread. Subtracting sender CPU from receiver CPU would not measure either.
//! All observations travel with completed replies, including NothingNew answers,
//! so an idle or synchronized-output turn cannot silently disappear from the tail.
//!
//! The report is generated by a fresh optimized flood witness during acceptance.
//! Its exact test name must appear with an ok result, since Cargo also succeeds
//! when a filter matches no tests. Missing arrays or malformed fields are failures.
//! Queue and owner wall durations must partition the full request wall interval.
//! Late answers are counted against the caller-supplied deadline, never classified
//! against an independently invented timeout. CPU absence stays explicit on
//! unsupported platforms; a supported Unix clock must supply every paired sample.
//! Raw chronological pairs remain in target/m16-5/flood-publications.json for
//! reviewing individual late answers instead of inferring causes from percentiles.
use super::{super::report, desktop_test};
use std::fs;

#[cfg(test)]
/// Report validation must reject missing evidence rather than accepting an empty run.
mod tests;

/// Runs the finite flood before reading its chronological publication samples.
pub(in crate::accept) fn publication_distribution() -> Result<(), String> {
    let name = "session_thread::tests::capture::flood_request_publication_distribution";
    // Rebuild and run the exact production owner; old JSON alone is insufficient.
    let output = crate::commands::capture(
        "cargo",
        &[
            // The diagnostic feature reads thread CPU without affecting default builds.
            "test",
            "--release",
            "-p",
            "puzzle-embed",
            "--features",
            "lock-metrics",
            name,
            "--",
            "--exact",
            "--nocapture",
        ],
    )?;
    if !output.contains(&format!("test {name} ... ok")) {
        return Err("owner flood publication test did not run".into());
    }
    let bytes =
        fs::read("target/m16-5/flood-publications.json").map_err(|error| error.to_string())?;
    let value: serde_json::Value =
        serde_json::from_slice(&bytes).map_err(|error| error.to_string())?;
    // Empty reports fail even if the test runner itself reported a successful exit.
    summarize(value.as_array().ok_or("publication array missing")?)
}

/// Every answer is checked; percentiles never choose only punctual publications.
fn summarize(rows: &[serde_json::Value]) -> Result<(), String> {
    if rows.is_empty() {
        return Err("empty publication observations".into());
    }
    // Allocate summaries after the producer has stopped; this does not time formatting.
    let mut wall = Vec::with_capacity(rows.len());
    // CPU samples cover only the owner interval, not time spent waiting in a channel.
    let mut cpu = Vec::with_capacity(rows.len());
    // Late is a count of answers, including unchanged ones, rather than dropped frames.
    let mut late = 0;
    for row in rows {
        let (total, paired_cpu, after_deadline) = observation(row)?;
        // Each row contributes to the full wall cohort, whether punctual or late.
        if let Some(value) = paired_cpu {
            cpu.push(value);
        }
        late += usize::from(after_deadline);
        wall.push(total);
    }
    // Sort copied scalar values only; the chronological source report remains intact.
    wall.sort_by(f64::total_cmp);
    cpu.sort_by(f64::total_cmp);
    // Full latency includes queue residence; CPU covers only the same owner's work.
    // Every percentile uses the entire sorted cohort with the maximum kept separately.
    // Five or fewer samples still retain their observed tail rather than interpolating it.
    println!(
        "D-50 publication samples={} late={} request wall p50/p99/max={:.6}/{:.6}/{:.6} ms; owner CPU p50/p99/max={:?}",
        rows.len(),
        late,
        wall[(wall.len() - 1) / 2],
        wall[(wall.len() - 1) * 99 / 100],
        wall[wall.len() - 1],
        (!cpu.is_empty()).then(|| [
            cpu[(cpu.len() - 1) / 2],
            cpu[(cpu.len() - 1) * 99 / 100],
            cpu[cpu.len() - 1]
        ])
    );
    Ok(())
}

/// Verifies one inseparable queue/owner pair without imposing a new budget.
fn observation(row: &serde_json::Value) -> Result<(f64, Option<f64>, bool), String> {
    let total = number(row, "request_to_publish_wall_ms")?;
    let queue = number(row, "control_wait_wall_ms")?;
    let work = number(row, "applied_to_publish_wall_ms")?;
    // Floating serialization may round sub-nanosecond fractions of a millisecond.
    // This checks interval identity, not a latency threshold or allowed late count.
    if (total - queue - work).abs() > 1e-9 {
        return Err("publication intervals do not partition the request".into());
    }
    let cpu = if row["applied_to_publish_thread_cpu_ms"].is_null() {
        // A missing platform clock remains an absence, never a reported zero cost.
        if cfg!(unix) {
            return Err("owner thread CPU clock absent on Unix".into());
        }
        None
    } else {
        Some(number(row, "applied_to_publish_thread_cpu_ms")?)
    };
    // A truncated report lacking the deadline classification cannot satisfy this row.
    let late = row["published_after_build_deadline"]
        .as_bool()
        .ok_or("publication deadline flag absent")?;
    Ok((total, cpu, late))
}

/// Missing, negative or nonfinite fields cannot satisfy an observation criterion.
fn number(row: &serde_json::Value, key: &str) -> Result<f64, String> {
    // Typed JSON numbers distinguish a missing field from a genuine zero-duration turn.
    // Reject invalid units before sorting, where NaN could otherwise give a misleading rank.
    row[key]
        .as_f64()
        .filter(|value| value.is_finite() && *value >= 0.0)
        .ok_or_else(|| format!("invalid publication {key}"))
}

/// Reports independent behavior, structural ownership and fresh publication evidence.
pub(super) fn report_parse(passed: &mut bool) {
    report(
        "M6-T3 control messages apply between available 16 KiB slices (D-50)",
        desktop_test(
            "session_thread::tests::pipeline::available_slices_apply_controls_at_each_boundary",
        ),
        passed,
    );
    report(
        "M6-T3 control handoff survives 100000 races (D-50)",
        desktop_test("session_thread::tests::pipeline::hundred_thousand_control_handoffs_finish"),
        passed,
    );
    // D-50 §15.2 explicitly replaces the two shared-lock rows, retaining every
    // other mechanical behavior and its existing end-to-end timing budget.
    report(
        "D-50 main/render never wait for a Session by construction",
        crate::lint::session::check(),
        passed,
    );
    report(
        "D-50 frame request publications record wall/CPU distribution and late count",
        publication_distribution(),
        passed,
    );
    report(
        "M6-T3 real PTY DA then CPR reply order",
        desktop_test("session_thread::tests::pipeline::real_pty_da_cpr_reply_order"),
        passed,
    );
}
