//! Typed settings schema and layered, validated session configuration (§14).
//!
//! Every external source enters as the bus's neutral Value tree. The schema
//! decides types and bounds once; the store then resolves user, profile and
//! session layers without a JSON dependency in platform-neutral code.
/// Converts validated fields into Session's current live policies.
mod config;
/// One source of setting keys, defaults, validators and documentation.
pub mod schema;
/// Layer resolution, validation reports and profile activation.
pub mod store;
/// Platform-neutral value conversion and bounded validators.
mod value;

/// Settings use the same wire tree as public bus messages (D-26).
pub type SettingsValue = puzzle_bus::Value;
/// Typed effective values generated by the schema DSL.
pub use schema::{
    ApplyMode, BlinkMode, Platform, SettingDef, Settings, ShiftCapture, ThemeMode, Validator,
};
/// Reconciles defaults, user, profile and session layers.
pub use store::{ApplyReport, Layer, SettingsStore};
