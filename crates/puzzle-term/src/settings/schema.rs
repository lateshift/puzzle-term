//! One macro declaration emits typed settings and their public metadata.
//!
//! A field's external camelCase key, default and validator occur in one
//! entry. The same entry drives runtime assignment and generated docs, so
//! a new setting cannot silently omit validation or documentation.
//! The catalogue is data, while this module defines the DSL expansion.
//! Keeping them separate makes the generated typed struct easy to audit
//! without duplicating a second, manually maintained schema table.
use super::value::{SettingValue, validate};
use puzzle_bus::Value;
/// The complete M6 catalogue, kept separate from macro machinery for R7.
mod catalogue;
pub use catalogue::Settings;
/// Application-overridable and user-forced Shift policies.
mod shift_capture;
pub use shift_capture::ShiftCapture;

/// Whether changing a setting takes effect now or at the next start.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum ApplyMode {
    /// Recompute only the affected live subsystem.
    Live,
    /// Preserve the choice but recreate the resource on the next session.
    NextSession,
}

/// Platforms that may expose a setting to their public adapters.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum Platform {
    /// The neutral core and both shells recognize the key.
    All,
    /// Only the browser adapter offers this key.
    Web,
    /// Only the native shell offers this key.
    Desktop,
}

/// Validation applied before conversion into a typed field.
#[derive(Clone, Copy, Debug)]
pub enum Validator {
    /// The field's typed codec supplies its remaining type and size checks.
    Any,
    /// Clamp numeric input into an explicit inclusive range.
    Range {
        /// Inclusive lower numeric bound.
        minimum: f64,
        /// Inclusive upper numeric bound.
        maximum: f64,
    },
    /// Reject a string outside a stable enum catalogue.
    Choice(&'static [&'static str]),
    /// Accept a cursor palette source or exactly six hexadecimal RGB digits.
    CursorColor,
}

/// Documentation and validation policy for one external key.
#[derive(Clone, Debug)]
pub struct SettingDef {
    /// Stable dotted camelCase path in JSON, JS and CLI.
    pub key: &'static str,
    /// Type name generated by the field's wire codec.
    pub kind: &'static str,
    /// Schema default in the shared plain-data representation.
    pub default: Value,
    /// Explanation retained from the field's source documentation.
    pub doc: &'static str,
    /// First dotted component for grouped docs and UI controls.
    pub group: &'static str,
    /// Whether a live instance can apply the change immediately.
    pub apply: ApplyMode,
    /// Adapter availability, independent of the neutral schema.
    pub platform: Platform,
    /// Numeric or enum rule shared by every settings source.
    pub validator: Validator,
}

/// Resolves the system appearance or an explicit light/dark setting.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum ThemeMode {
    /// Follow the host's appearance notification.
    Auto,
    /// Use the configured light theme regardless of the host.
    Light,
    /// Use the configured dark theme regardless of the host.
    Dark,
}

/// Cursor blink policy; Auto defers to the application's cursor request.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum BlinkMode {
    /// Follow DECSCUSR and mode ?12.
    Auto,
    /// Blink regardless of the application's steady style.
    On,
    /// Keep the cursor steady regardless of the application's request.
    Off,
}

impl SettingValue for BlinkMode {
    /// JSON accepts the default policy or a forced boolean.
    const KIND: &'static str = "auto|boolean";
    /// Rejects strings other than auto so a typo cannot force blinking.
    fn decode(value: &Value) -> Result<Self, String> {
        match value {
            Value::String(text) if text == "auto" => Ok(Self::Auto),
            Value::Bool(true) => Ok(Self::On),
            Value::Bool(false) => Ok(Self::Off),
            _ => Err("expected auto, true or false".into()),
        }
    }
    /// The wire form matches the documented JSON setting.
    fn encode(&self) -> Value {
        match self {
            Self::Auto => Value::String("auto".into()),
            Self::On => Value::Bool(true),
            Self::Off => Value::Bool(false),
        }
    }
}

impl SettingValue for ThemeMode {
    /// Wire metadata enumerates the only appearances this build accepts.
    const KIND: &'static str = "auto|light|dark";
    /// Rejects unknown appearance names before they reach theme selection.
    fn decode(value: &Value) -> Result<Self, String> {
        match value {
            Value::String(text) if text == "auto" => Ok(Self::Auto),
            Value::String(text) if text == "light" => Ok(Self::Light),
            Value::String(text) if text == "dark" => Ok(Self::Dark),
            _ => Err("expected auto, light or dark".into()),
        }
    }
    /// Exports the same names accepted by desktop JSON and future JS.
    fn encode(&self) -> Value {
        Value::String(
            match self {
                Self::Auto => "auto",
                Self::Light => "light",
                Self::Dark => "dark",
            }
            .into(),
        )
    }
}

/// Declares a typed field once and emits its default, metadata and setter.
///
/// The same `$doc` feeds Rust fields and generated UI metadata. A missing
/// declaration therefore cannot produce an undocumented setting in only
/// one of the two public surfaces (§14.1).
macro_rules! define_settings {
    ($(#[doc = $doc:literal] $field:ident : $ty:ty = $default:expr => $key:literal, $rule:expr, $apply:ident, $platform:ident;)+) => {
        /// Validated effective configuration with concrete Rust field types.
        #[derive(Clone, Debug, PartialEq)]
        pub struct Settings {
            $(#[doc = $doc] pub $field: $ty,)+
        }

        impl Default for Settings {
            /// Builds the schema's defaults without a platform file or parser.
            fn default() -> Self {
                Self { $($field: $default,)+ }
            }
        }

        impl Settings {
            /// Returns all documented keys in declaration order.
            #[must_use]
            pub fn schema() -> Vec<super::SettingDef> {
                let defaults = Self::default();
                vec![$(super::SettingDef {
                    key: $key,
                    kind: <$ty as super::SettingValue>::KIND,
                    default: defaults.$field.encode(),
                    doc: $doc,
                    group: $key.split_once('.').map_or($key, |(group, _)| group),
                    apply: super::ApplyMode::$apply,
                    platform: super::Platform::$platform,
                    validator: $rule,
                },)+]
            }

            /// Reads a typed field through the neutral wire representation.
            #[must_use]
            pub fn value(&self, key: &str) -> Option<Value> {
                match key {
                    $($key => Some(self.$field.encode()),)+
                    _ => None,
                }
            }

            /// Validates and assigns a known key, reporting a numeric clamp.
            pub(crate) fn assign(&mut self, key: &str, value: Value) -> Result<bool, String> {
                match key {
                    $($key => {
                        let (value, clamped) = super::validate(value, $rule)?;
                        self.$field = <$ty as super::SettingValue>::decode(&value)?;
                        Ok(clamped)
                    },)+
                    _ => Err("unknown schema key".into()),
                }
            }
        }
    };
}
pub(super) use define_settings;

