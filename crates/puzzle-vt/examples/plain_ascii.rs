//! Test-only native throughput probe for the M5.2 ASCII parser budget.
//!
//! The production puzzle-vt library remains clock-free; this example owns
//! timing and writes one machine-readable result for `cargo xtask corpus`.
//! Its input has full-width ASCII rows and LF, so it measures vte decoding,
//! grid writes and steady ring scrolling together (§15.2, P1).
use puzzle_vt::Terminal;
use std::{hint::black_box, time::Instant};

/// Corpus bytes per sample, large enough to amortize timer overhead.
const CORPUS_BYTES: usize = 8 * 1024 * 1024;

/// Repeats the xtask-generated source without cutting its 80-byte rows.
fn corpus() -> std::io::Result<Vec<u8>> {
    // The checked-in source is generated by xtask and consists of whole
    // CR/LF records; repeating it preserves exact parser boundaries.
    let source = std::fs::read("assets/fixtures/corpus/plain-ascii.vt")?;
    if source.is_empty() {
        return Err(std::io::Error::new(
            std::io::ErrorKind::InvalidData,
            "empty ASCII corpus",
        ));
    }
    let mut bytes = Vec::with_capacity(CORPUS_BYTES + source.len());
    while bytes.len() < CORPUS_BYTES {
        bytes.extend_from_slice(&source);
    }
    Ok(bytes)
}

/// Reports the median native MB/s across repeated hot-cache feeds.
fn main() -> std::io::Result<()> {
    let bytes = corpus()?;
    let mut terminal = Terminal::new(80, 24, 100, 80 * 16 * 100);
    // Warm the parser, grid and scrollback before any timed sample.
    terminal.advance(&bytes[..80 * 200]);
    let mut rates = [0.0_f64; 5];
    for rate in &mut rates {
        let started = Instant::now();
        terminal.advance(black_box(&bytes));
        let seconds = started.elapsed().as_secs_f64();
        // Decimal megabytes match the §15.2 budget's MB/s unit.
        *rate = bytes.len() as f64 / seconds / 1_000_000.0;
    }
    rates.sort_by(f64::total_cmp);
    // This artifact is written after timing, keeping file I/O outside the
    // measured byte path and the production terminal library clock-free.
    std::fs::create_dir_all("target/corpus")?;
    std::fs::write(
        "target/corpus/plain-ascii-mbps.txt",
        format!("{:.3}\n", rates[2]),
    )?;
    Ok(())
}
