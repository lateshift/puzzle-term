//! Pool tests use a generated 100 MB stream without a 100 MB allocation.
//!
//! The producer computes a position-sensitive checksum as it fills each
//! reusable vector; the consumer computes the same checksum after channel
//! transfer and 16 KiB slicing. Lost, repeated or reordered bytes change
//! that result. A separate idle-pool test measures only warmed transfers,
//! excluding the one-time 4 MiB allocation from the steady-state rule.
use super::*;
/// Host admission preserves the fixed-pool guarantees under nonblocking backpressure.
mod admission;
use std::{
    io::Cursor,
    sync::atomic::{AtomicUsize, Ordering},
    thread,
    time::{Duration, Instant},
};

/// Total stream size is decimal 100 MB as required by T2.
const TEST_BYTES: usize = 100_000_000;
/// FNV offset basis gives position-sensitive rolling evidence.
const HASH_START: u64 = 0xcbf2_9ce4_8422_2325;
/// FNV prime mixes each incoming byte with prior order.
const HASH_PRIME: u64 = 0x0000_0100_0000_01b3;

/// Generates a deterministic byte at any absolute stream position.
fn pattern(index: usize) -> u8 {
    ((index as u64).wrapping_mul(31) ^ ((index as u64) >> 11)) as u8
}

/// Updates the ordered checksum without retaining the whole corpus.
fn hash(current: u64, byte: u8) -> u64 {
    (current ^ u64::from(byte)).wrapping_mul(HASH_PRIME)
}

/// A finite fake PTY that reports how far its blocking reader advanced.
struct PatternReader {
    /// Next generated byte offset.
    position: usize,
    /// Total byte count before EOF.
    length: usize,
    /// Producer checksum returned by the thread at EOF.
    checksum: u64,
    /// Progress lets the backpressure test observe a blocked read.
    progress: Arc<AtomicUsize>,
}

impl Read for PatternReader {
    /// Fills one pool buffer from a deterministic position-dependent stream.
    fn read(&mut self, output: &mut [u8]) -> std::io::Result<usize> {
        let count = output.len().min(self.length - self.position);
        for (offset, cell) in output[..count].iter_mut().enumerate() {
            *cell = pattern(self.position + offset);
            self.checksum = hash(self.checksum, *cell);
        }
        self.position += count;
        self.progress.store(self.position, Ordering::Release);
        Ok(count)
    }
}

/// A 100 MB transfer preserves byte order and never exceeds pool capacity.
#[test]
fn hundred_mb_checksum_and_bound() {
    let (mut producer, mut consumer) = pair();
    let progress = Arc::new(AtomicUsize::new(0));
    let producer_progress = Arc::clone(&progress);
    let worker = thread::spawn(move || {
        let mut reader = PatternReader {
            position: 0,
            length: TEST_BYTES,
            checksum: HASH_START,
            progress: producer_progress,
        };
        while producer
            .read_once(&mut reader)
            .is_ok_and(|has_bytes| has_bytes)
        {}
        reader.checksum
    });
    let mut consumed = 0;
    let mut received_hash = HASH_START;
    while consumed < TEST_BYTES {
        if let Some(bytes) = consumer.next_slice() {
            for byte in bytes {
                received_hash = hash(received_hash, *byte);
            }
            let count = bytes.len();
            assert!(consumer.consume(count).is_ok());
            consumed += count;
        } else {
            thread::yield_now();
        }
    }
    assert_eq!(worker.join().ok(), Some(received_hash));
    assert_eq!(progress.load(Ordering::Acquire), TEST_BYTES);
    assert_eq!(consumer.pending_bytes(), 0);
    assert!(consumer.peak_bytes() <= POOL_COUNT * BUFFER_SIZE);
}

/// Exhausting the pool blocks the next read until a buffer is returned.
#[test]
fn producer_waits_for_an_empty_buffer() {
    let (mut producer, mut consumer) = pair();
    let progress = Arc::new(AtomicUsize::new(0));
    let worker_progress = Arc::clone(&progress);
    let worker = thread::spawn(move || {
        let mut reader = PatternReader {
            position: 0,
            length: (POOL_COUNT + 2) * BUFFER_SIZE,
            checksum: HASH_START,
            progress: worker_progress,
        };
        while producer
            .read_once(&mut reader)
            .is_ok_and(|has_bytes| has_bytes)
        {}
    });
    let deadline = Instant::now() + crate::test_support::HANG_GUARD;
    while progress.load(Ordering::Acquire) < POOL_COUNT * BUFFER_SIZE && Instant::now() < deadline {
        thread::yield_now();
    }
    assert_eq!(progress.load(Ordering::Acquire), POOL_COUNT * BUFFER_SIZE);
    thread::sleep(Duration::from_millis(10));
    assert_eq!(progress.load(Ordering::Acquire), POOL_COUNT * BUFFER_SIZE);
    for _ in 0..(POOL_COUNT + 2) * (BUFFER_SIZE / SLICE_SIZE) {
        // Returning each consumed buffer permits exactly one more read;
        // no byte is dropped to relieve a full producer.
        loop {
            if let Some(bytes) = consumer.next_slice() {
                let count = bytes.len();
                assert!(consumer.consume(count).is_ok());
                break;
            }
            thread::yield_now();
        }
    }
    assert_eq!(
        progress.load(Ordering::Acquire),
        (POOL_COUNT + 2) * BUFFER_SIZE
    );
    assert!(worker.join().is_ok());
}

/// Warm transfer and return make no heap requests in the desktop binary.
#[test]
fn warm_handoff_allocates_nothing() {
    let (mut producer, mut consumer) = pair();
    let data = [0x5a; BUFFER_SIZE];
    let measured = allocation_counter::measure(|| {
        for _ in 0..128 {
            let mut reader = Cursor::new(data.as_slice());
            assert!(
                producer
                    .read_once(&mut reader)
                    .is_ok_and(|has_bytes| has_bytes)
            );
            for _ in 0..4 {
                let Some(bytes) = consumer.next_slice() else {
                    panic!("pool did not return a just-produced buffer");
                };
                let count = bytes.len();
                assert!(consumer.consume(count).is_ok());
            }
        }
    });
    assert_eq!(measured.count_total, 0, "warm pool allocated: {measured:?}");
    assert_eq!(consumer.pending_bytes(), 0);
}

/// Cloned control senders must not hide EOF or make a full drain destructor block.
#[test]
fn eof_after_full_queue_and_wakes_preserves_every_byte() {
    let (mut producer, mut consumer) = pair();
    let wake = consumer.wake_handle();
    let data = [0x71; BUFFER_SIZE];
    for _ in 0..POOL_COUNT {
        assert!(
            producer
                .read_once(&mut Cursor::new(data.as_slice()))
                .unwrap_or_else(|error| panic!("{error:?}"))
        );
    }
    // A saturated inbox drops redundant wake tokens, never accepted payloads.
    for _ in 0..POOL_COUNT {
        wake.notify();
    }
    // EOF is observable without blocking behind the full data queue.
    drop(producer);
    let mut count = 0;
    while let Some(bytes) = consumer.next_slice_blocking() {
        assert!(bytes.iter().all(|byte| *byte == 0x71));
        let length = bytes.len();
        consumer
            .consume(length)
            .unwrap_or_else(|error| panic!("{error:?}"));
        count += length;
    }
    assert_eq!(count, POOL_COUNT * BUFFER_SIZE);
    assert!(consumer.closed());
}
