//! TypeScript patch keys mirror the Rust `define_settings!` catalogue.
//!
//! Quoted dotted keys match the public settings API's `get` and `set`
//! operations. The JSON Schema separately describes nested config.json;
//! consumers may use this patch map for a typed dynamic settings editor.
//! Validator choices become string unions, so misspellings are visible in
//! TypeScript before the runtime's validation report is needed.
//! A patch is sparse: callers may change one key without manufacturing an
//! entire nested config object. The runtime still returns an ApplyReport
//! for rejection or clamping, so these types describe accepted shapes
//! rather than promising that every number is within its runtime range.
use puzzle_term::settings::{SettingDef, Validator};

/// Emits every key, including recent cursor, session and logging fields.
pub(super) fn document(definitions: &[SettingDef]) -> String {
    let mut output = String::from(
        "// Generated by `cargo xtask settings-docs` from Settings::schema().\n\nexport interface SettingsPatch {\n",
    );
    for definition in definitions {
        // Documentation follows its field declaration so hover text and
        // JSON Schema give the same explanation for one setting.
        output.push_str(&format!("  /** {} */\n", definition.doc));
        output.push_str(&format!(
            "  '{}'? : {};\n",
            definition.key,
            kind(definition)
        ));
    }
    output.push_str("}\n\nexport type SettingsKey = keyof SettingsPatch;\n");
    output.push_str(
        "export type SettingsValue<K extends SettingsKey> = NonNullable<SettingsPatch[K]>;\n",
    );
    output.push_str("// Platform default bindings are documented in docs/SETTINGS.md (§14.9).\n");
    output
}

/// Uses validator choices where the Rust codec accepts a closed enum.
fn kind(definition: &SettingDef) -> String {
    if let Validator::Choice(options) = definition.validator {
        // An empty choice would be an invalid schema declaration; the
        // generated union still remains syntactically valid if one arrives.
        return options
            .iter()
            .map(|option| format!("'{option}'"))
            .collect::<Vec<_>>()
            .join(" | ");
    }
    match definition.kind {
        "boolean" => "boolean".into(),
        "number" | "integer" => "number".into(),
        "string[]" => "string[]".into(),
        "object" => "Record<string, unknown>".into(),
        "auto|boolean" => "'auto' | boolean".into(),
        "boolean|always|never" => "boolean | 'always' | 'never'".into(),
        _ => "string".into(),
    }
}
