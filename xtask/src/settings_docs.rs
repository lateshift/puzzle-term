//! Generated settings reference from the `define_settings!` catalogue.
//!
//! The schema supplies external keys, typed defaults, validation and docs
//! from one Rust declaration. This generator merely translates that data
//! into Markdown, JSON Schema and a TypeScript key map. No second list of
//! settings names is maintained here, so an added field changes all three
//! outputs and `cargo xtask check` catches a stale checked-in artifact.
//!
//! The desktop writes an adjacent editor schema for `--init-config`; the
//! repository copy is the stable version used by docs and the web package.
//! Unknown JSON keys remain allowed because older Puzzle versions preserve
//! them instead of destroying a newer user's config on save (§14.4).
//!
//! Generated artifacts are committed so an offline checkout still has
//! editor completion and public types before Cargo builds the native
//! generator. Check mode renders entirely in memory and compares bytes;
//! it must not rewrite files, because a stale output is a reviewable error.
//! The `settings-docs` command also refreshes the pre-existing bus
//! reference, whose active names change when a typed message arrives.
//!
//! Defaults are converted from the neutral Value tree, not parsed from
//! the source file's Rust syntax. A string that looks like a number
//! therefore stays a string in JSON and in the Markdown default column.
//! Each setting's group is supplied by the schema metadata. A new dotted
//! key automatically lands under its group without editing this module.
//! Portable shortcut tables and action metadata supply the binding reference;
//! a new core action therefore cannot leave a hand-maintained guide stale.
use puzzle_term::settings::{ApplyMode, Platform, SettingDef, Settings, SettingsValue, Validator};
use serde_json::Value as Json;
use std::{fs, path::Path};
/// Platform binding descriptions shared by guide and TypeScript comments.
mod platform;
/// Draft 2020-12 JSON Schema translation from typed setting definitions.
mod schema;
/// Dotted-key types for settings patches and config editor APIs.
mod types;

/// Converts the schema's plain Value defaults into JSON document values.
fn to_json(value: &SettingsValue) -> Json {
    // Exact typed defaults are small. Recursive conversion mirrors the
    // nested lists and maps that config.json allows for user profiles.
    match value {
        SettingsValue::Null => Json::Null,
        SettingsValue::Bool(value) => Json::Bool(*value),
        // All typed defaults are finite. Null still makes the conversion
        // total if a future direct Rust caller constructs an invalid value.
        SettingsValue::Number(value) => serde_json::Number::from_f64(*value)
            .map(Json::Number)
            .unwrap_or(Json::Null),
        // Strings are copied literally, including escape characters in
        // default keybindings and platform-dependent path placeholders.
        SettingsValue::String(value) => Json::String(value.clone()),
        // Bytes have no config.json spelling; no current setting uses them.
        SettingsValue::Bytes(_) => Json::Null,
        // List order is semantic for font fallbacks and binding priority.
        SettingsValue::List(values) => Json::Array(values.iter().map(to_json).collect()),
        SettingsValue::Map(values) => Json::Object(
            values
                .iter()
                .map(|(key, value)| (key.clone(), to_json(value)))
                .collect(),
        ),
    }
}

/// Renders a stable, grouped settings guide with every current schema key.
fn markdown(definitions: &[SettingDef]) -> String {
    // The heading names the generation source so readers can reproduce
    // the table after a setting is added to `define_settings!`.
    let mut output = String::from(
        "# Puzzle Terminal settings\n\nGenerated by `cargo xtask settings-docs` from `Settings::schema()` (§14.8). Defaults are product defaults; `cargo xtask run` uses its documented 15 px harness override until a setting chooses `font.size`.\n\n",
    );
    let mut group = "";
    for definition in definitions {
        // Group boundaries come from the first dotted component; this
        // remains stable if a field is reordered inside one group.
        if definition.group != group {
            group = definition.group;
            output.push_str(&format!("## {group}\n\n| Key | Type | Default | Validation | Apply | Platforms | Description |\n|---|---|---|---|---|---|---|\n"));
        }
        // Markdown pipes in an enum or description must not create new
        // table columns; generated docs are browsable without a renderer.
        let kind = definition.kind.replace('|', "\\|");
        // JSON spelling makes null, strings and string arrays unambiguous
        // in a narrow Markdown cell without inventing a prose formatter.
        let default = to_json(&definition.default).to_string().replace('|', "\\|");
        let validation = validation(definition.validator).replace('|', "\\|");
        let apply = match definition.apply {
            ApplyMode::Live => "live",
            ApplyMode::NextSession => "next session",
        };
        let platform = match definition.platform {
            Platform::All => "all",
            Platform::Web => "web",
            Platform::Desktop => "desktop",
        };
        // The doc string is the Rust field's source comment, so generated
        // docs never silently omit a new typed setting.
        output.push_str(&format!(
            "| `{}` | {} | `{}` | {} | {} | {} | {} |\n",
            definition.key,
            kind,
            default,
            validation,
            apply,
            platform,
            definition.doc.replace('|', "\\|")
        ));
    }
    output.push_str("\n## Platform default bindings\n\nThese bindings apply before the terminal key encoder. User `keyboard.bindings` entries override the host table (§14.9). Copy entries are performable once selection arrives in M8.\n\n");
    // Host tables are included after scalar settings because they are
    // a policy layer, not the schema default for `keyboard.bindings`.
    output.push_str(&platform::document());
    output
}

/// Describes the same range or choice accepted by the typed validator.
fn validation(rule: Validator) -> String {
    // Editor-facing ranges distinguish clamping from strict enum rejection;
    // the runtime ApplyReport carries the exact result of an edit.
    match rule {
        Validator::Any => "typed value".into(),
        Validator::Range { minimum, maximum } => format!("{minimum}..{maximum} (clamped)"),
        Validator::Choice(values) => values.join(" | "),
        Validator::CursorColor => "theme | inverse | #rrggbb".into(),
    }
}

/// Builds all artifacts in memory before writing any destination.
fn render() -> Result<[(String, String); 3], String> {
    // Capture one metadata vector so all three artifacts describe the
    // same declaration order even if a future generator adds filtering.
    let definitions = Settings::schema();
    let markdown = markdown(&definitions);
    let schema = serde_json::to_string_pretty(&schema::document(&definitions))
        .map_err(|error| error.to_string())?
        + "\n";
    // A final newline keeps diffs and command-line tools deterministic.
    let types = types::document(&definitions);
    Ok([
        ("docs/SETTINGS.md".into(), markdown),
        ("docs/settings.schema.json".into(), schema),
        ("crates/puzzle-web/types/settings.d.ts".into(), types),
    ])
}

/// Regenerates bus and settings references in one documented command.
pub(crate) fn run() -> Result<(), String> {
    let artifacts = render()?;
    // Keep the existing M1 bus contract under this command while adding
    // settings outputs; one invocation refreshes every public reference.
    crate::bus_docs::run()?;
    for (path, content) in artifacts {
        // All destination roots are repository-owned. No user config is
        // overwritten by the documentation command.
        let path = Path::new(&path);
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent).map_err(|error| error.to_string())?;
        }
        fs::write(path, content).map_err(|error| error.to_string())?;
    }
    Ok(())
}

/// Rejects a stale generated reference without modifying the working tree.
pub(crate) fn check() -> Result<(), String> {
    // Compare exact content rather than mtimes: checkout timestamps can
    // differ from source timestamps while generated bytes remain correct.
    for (path, expected) in render()? {
        if fs::read_to_string(&path).map_err(|error| format!("{path}: {error}"))? != expected {
            return Err(format!("generated settings reference is stale: {path}"));
        }
    }
    Ok(())
}
