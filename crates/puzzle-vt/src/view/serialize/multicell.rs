//! Rectangular persistence positions source rows explicitly around reservations.
//! A private parser mirror tracks scrolling caused by wrap and OSC 66 placement.
//! It is a cold serialization allocation, never part of feed or frame assembly.
//!
//! Ordinary VT serialization can print each logical row in sequence. Rectangles
//! reserve future rows, so replaying that way would skip cells or overwrite ink.
//! This writer restores physical coordinates explicitly and observes its own
//! generated stream through a private Terminal. That reuses the real placement
//! and scroll rules instead of maintaining a second approximation of them.
//! Missing root fragments require temporary prefix rows. The full operation is
//! emitted there once, then those rows are retired from the reconstructed buffer.
//! Fragment offsets therefore remain meaningful for a clipped heading in history.
//! The mirror and its scratch vectors exist only for an explicit persistence
//! request; none belongs to the normal parser, snapshot or frame-building path.
use super::*;
use crate::{Terminal, multicell::Multicell};

/// Rich snippets emit a selected lower fragment once, like plain copy.
pub(super) mod selection;
/// Wrap preparation handles lower reservations without overwriting their owner.
mod wrapping;

/// A retained owner is emitted once, including a root above the exported range.
struct Record<'a> {
    /// Virtual source row before the artificial clipped-root prefix is discarded.
    root: usize,
    /// Text and geometry remain borrowed from the source terminal.
    block: &'a Multicell,
    /// First retained fragment supplies the same inherited rendition.
    line: LineView<'a>,
}

/// Parser-observed output cursor avoids duplicating print/skip/scroll semantics.
struct Writer<'a> {
    /// Source physical rows are stable for this entire explicit export.
    lines: Vec<LineView<'a>>,
    /// Distinct records, in source owner order.
    records: Vec<Record<'a>>,
    /// Generated escape bytes returned to the caller.
    output: String,
    /// Replaying only generated bytes observes the destination's physical cursor.
    mirror: Terminal,
    /// Monotonic initial visible identity converts mirror rows into virtual rows.
    origin: u64,
    /// Missing original root rows are temporarily reconstructed, then discarded.
    prefix: usize,
    /// Wrap bits prepared on blank destination rows before rectangle installation.
    prepared: Vec<bool>,
    /// A visible right-edge owner is emitted last to restore delayed wrap once.
    pending: Option<usize>,
}

/// Wire emission and the mirror always advance together.
impl<'a> Writer<'a> {
    /// Gathers sparse records once; no source slot escapes into the VT stream.
    fn new(view: BufferView<'a>, range: RangeInclusive<LineId>, output: String) -> Self {
        let lines: Vec<_> = view.lines(range).collect();
        let (records, prefix) = records(&lines);
        let pending = view
            .cursor()
            .filter(|cursor| cursor.pending_wrap)
            .and_then(|cursor| {
                // CUP clears delayed wrap. Defer this one owner so its placement
                // itself recreates the cursor's final right-edge state.
                let block = view.line(cursor.line)?.multicell(cursor.column)?;
                records
                    .iter()
                    .position(|record| std::ptr::eq(record.block, block))
            });
        let (width, height) = view.size();
        let mut mirror = Terminal::new(width, height, lines.len() + height + prefix, usize::MAX);
        // The initial header resets and selects the same destination screen as
        // ordinary persistence. Observe it before computing virtual line offsets.
        mirror.advance(output.as_bytes());
        let origin = mirror.screen().ring.visible(0).map_or(0, |row| row.id.0);
        let prepared = vec![false; lines.len() + prefix];
        // Each virtual row's wrap preparation is idempotent even if several
        // roots reserve it. This avoids erasing a rectangle installed earlier.
        Self {
            lines,
            records,
            output,
            mirror,
            origin,
            prefix,
            prepared,
            pending,
        }
    }
    /// A single seam keeps the serialized stream and its observed cursor identical.
    fn push(&mut self, bytes: &str) {
        self.output.push_str(bytes);
        self.mirror.advance(bytes.as_bytes());
    }
    /// Number of virtual source rows already scrolled above the visible grid.
    fn base(&self) -> usize {
        // Mirror line IDs advance monotonically as generated output scrolls.
        // Subtracting the initial identity converts them to source virtual rows.
        self.mirror
            .screen()
            .ring
            .visible(0)
            .map_or(0, |row| row.id.0.saturating_sub(self.origin) as usize)
    }
    /// Makes a future reservation fit without scrolling its root during placement.
    fn ensure(&mut self, last: usize) {
        let overflow = (last + 1).saturating_sub(self.base() + self.mirror.size().1);
        if overflow != 0 {
            // Explicit scrolling keeps the soon-to-be-written root visible;
            // otherwise bottom fitting could scroll it during OSC 66 placement.
            self.push(&format!("\x1b[0m\x1b[{overflow}S"));
        }
    }
    /// Writes a fully described rectangle once through the public kitty operation.
    fn record(&mut self, index: usize) {
        let record = &self.records[index];
        let block = record.block;
        let s = block.sizing;
        let cell = record.line.cells()[block.column];
        // Styles live inline in each covered cell. The first surviving fragment
        // supplies rendition even if the original owner was already evicted.
        let underline = record
            .line
            .cell(block.column)
            .and_then(|cell| cell.underline_color);
        // CUP addresses physical rows from the current mirror base, not source
        // LineIds: serialized terminals receive fresh monotonic identities.
        let mut bytes = format!(
            "\x1b[{};{}H{}",
            record.root - self.base() + 1,
            block.column + 1,
            sgr(cell, underline)
        );
        bytes.push_str(if cell.flags.contains(CellFlags::PROTECTED) {
            "\x1b[1\"q"
        } else {
            "\x1b[0\"q"
        });
        if let Some(uri) = record.line.cell(block.column).and_then(|cell| cell.link) {
            // Hyperlinks remain payload metadata, independent of private keys.
            bytes.push_str(&format!("\x1b]8;;{uri}\x1b\\"));
        }
        // An implicit cluster's stored width remains authoritative after mode changes.
        let clustered = unicode_width::UnicodeWidthStr::width(block.text.as_str()).clamp(1, 2)
            * usize::from(s.scale)
            == block.columns;
        bytes.push_str(if clustered {
            "\x1b[?2027h"
        } else {
            "\x1b[?2027l"
        });
        bytes.push_str(&format!(
            "\x1b]66;s={}:w={}:n={}:d={}:v={}:h={};{}\x1b\\",
            s.scale, s.width, s.numerator, s.denominator, s.vertical, s.horizontal, block.text
        ));
        bytes.push_str("\x1b]8;;\x1b\\");
        // Close the link explicitly so subsequent blanks do not inherit it.
        self.push(&bytes);
    }
    /// Reconstructs a row after preparing its future block fragments.
    fn row(&mut self, virtual_row: usize) {
        // Only roots originate an OSC operation. Lower fragments are rebuilt
        // by that operation, never by replaying duplicate payload text.
        let record_indices: Vec<_> = self
            .records
            .iter()
            .enumerate()
            .filter_map(|(i, record)| (record.root == virtual_row).then_some(i))
            .collect();
        let last = record_indices
            .iter()
            .map(|&i| virtual_row + usize::from(self.records[i].block.sizing.scale) - 1)
            .max()
            .unwrap_or(virtual_row);
        self.ensure(last);
        // Ensure capacity before writing any ordinary neighbour or block root;
        // scrolling halfway through the row would change their common origin.
        self.prepare_wraps(virtual_row, last);
        // Prepare lower-row wrap markers while those destinations are blank;
        // printing a wrap probe through a populated reservation would damage it.
        if let Some(line) = virtual_row
            .checked_sub(self.prefix)
            .and_then(|index| self.lines.get(index))
            .copied()
        {
            let row = virtual_row - self.base();
            let mut bytes = String::new();
            for column in 0..line.cells().len() {
                // Position ordinary cells independently around reservations.
                // Wide spacers and block keys are representation, not text.
                if !line.cells()[column]
                    .flags
                    .intersects(CellFlags::MULTICELL | CellFlags::WIDE_SPACER)
                {
                    write_cell(&mut bytes, row, column, line);
                }
            }
            self.push(&bytes);
        }
        // Rightmost roots are last, retaining delayed-wrap for a block at the edge.
        for index in record_indices {
            if Some(index) == self.pending {
                // This root is emitted after all physical rows are restored.
                continue;
            }
            self.record(index);
        }
        self.finish_wrap(virtual_row);
        // Ordinary right-margin state may require a final wrap-bit repair.
    }
}

/// Exports retained fragments using an artificial prefix only for missing roots.
pub(super) fn vt(view: BufferView<'_>, range: RangeInclusive<LineId>, output: String) -> String {
    let mut writer = Writer::new(view, range, output);
    for row in 0..writer.prefix + writer.lines.len() {
        if row == writer.prefix && writer.prefix != 0 {
            // Retire the artificial root rows, retaining the original lower offsets.
            let count = writer.prefix.saturating_sub(writer.base());
            if count != 0 {
                writer.push(&format!("\x1b[0m\x1b[{count}S"));
            }
            writer.push("\x1b[3J");
            // The synthetic prefix is not user scrollback. ED 3 removes it after
            // it has provided the missing original root's placement coordinates.
        }
        writer.row(row);
    }
    if let Some(index) = writer.pending {
        // Drawing this owner last restores pending-wrap without replaying its text
        // a second time. DECSC/DECRC carry the wrap flag across mode side effects.
        // DECSC restores DECOM too. Save the requested addressing mode rather
        // than the temporary full-screen mode used while reconstructing rows.
        if view.term.modes.get(true, 6) == Some(true) {
            writer.push("\x1b[?6h");
        }
        writer.record(index);
        writer.push("\x1b7");
        write_modes(view, &mut writer.output);
        writer
            .output
            .push_str(&format!("\x1b[{} q\x1b8", view.term.cursor_style));
    } else {
        // Non-block cursor restoration uses the existing ordinary serializer.
        // Only the deferred right-edge rectangle needs DECSC/DECRC above.
        write_modes(view, &mut writer.output);
        write_cursor(view, &mut writer.output);
    }
    writer.output
}

/// Collects logical owners and the prefix needed to reconstruct clipped roots.
fn records<'a>(lines: &[LineView<'a>]) -> (Vec<Record<'a>>, usize) {
    let mut records = Vec::new();
    let mut keys = Vec::new();
    let mut prefix = 0;
    for (index, line) in lines.iter().copied().enumerate() {
        // Sparse row indexes find records without interpreting cell keys as
        // Unicode. A retained lower fragment can be the first encountered row.
        for (key, block) in line.multicells() {
            if keys.contains(&key) {
                continue;
            }
            keys.push(key);
            let offset = block
                .fragments
                .iter()
                .find(|f| f.line == line.id())
                .map_or(0, |f| usize::from(f.offset));
            prefix = prefix.max(offset.saturating_sub(index));
            // Preserve source row order; this determines where surrounding
            // ordinary text is placed relative to each rectangle.
            records.push((index, offset, block, line));
        }
    }
    let records = records
        .into_iter()
        .map(|(index, offset, block, line)| Record {
            // Virtual roots include rows no longer present in the source.
            root: index + prefix - offset,
            block,
            line,
        })
        .collect();
    (records, prefix)
}
