//! Minimal draft 2020-12 schema for config.json editor completion (§14.4).
//!
//! Each property comes from the `define_settings!` metadata. Keeping this
//! generator at the native edge lets --init-config ship a local schema now;
//! M6.6's xtask generator will create the checked-in reference document.
use super::to_json;
use puzzle_term::settings::{Settings, Validator};
use serde_json::{Value as Json, json};

/// Builds nested JSON properties from dotted camelCase setting keys.
pub(in crate::settings) fn document() -> Json {
    // Editors use draft 2020-12 and tolerate future keys. The runtime
    // store still reports unknown keys but preserves them on save, so the
    // schema must not tell an editor to discard those values.
    let mut root = json!({
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "title": "Puzzle Terminal settings",
        "type": "object",
        "properties": {},
        "additionalProperties": true
    });
    for definition in Settings::schema() {
        // The metadata's kind is generated by the field's Rust codec.
        // This mapping only translates it into JSON Schema vocabulary;
        // it does not create a second list of setting names or defaults.
        let mut property = match definition.kind {
            "boolean" => json!({"type": "boolean"}),
            "number" => json!({"type": "number"}),
            "integer" => json!({"type": "integer"}),
            "string[]" => json!({"type": "array", "items": {"type": "string"}}),
            "object" => json!({"type": "object"}),
            // Cursor blink's auto choice is intentionally distinct from
            // forced true/false, so a string-only enum would be wrong.
            "auto|boolean" => json!({"anyOf": [{"const": "auto"}, {"type": "boolean"}]}),
            _ => json!({"type": "string"}),
        };
        property["description"] = Json::String(definition.doc.into());
        property["default"] = to_json(&definition.default);
        // Numeric bounds appear in the editor even though runtime policy
        // clamps rather than rejects a value outside the range.
        match definition.validator {
            Validator::Range { minimum, maximum } => {
                property["minimum"] = json!(minimum);
                property["maximum"] = json!(maximum);
            }
            // Choices reject typos at runtime, so completion should offer
            // the same stable strings instead of free-form text.
            Validator::Choice(values) => property["enum"] = json!(values),
            Validator::Any | Validator::CursorColor => {}
        }
        insert_property(&mut root, definition.key, property);
    }
    root
}

/// Creates object nodes only for path components preceding a leaf.
fn insert_property(root: &mut Json, key: &str, property: Json) {
    // The dot is a document nesting boundary, not part of a literal key;
    // `font.lineHeight` belongs under `font.properties.lineHeight`.
    let mut current = root;
    let mut parts = key.split('.').peekable();
    while let Some(part) = parts.next() {
        if parts.peek().is_none() {
            // Leaves replace only their own property; siblings that share
            // `font` or `cursor` remain in the same object.
            current["properties"][part] = property;
            return;
        }
        if current["properties"][part].is_null() {
            // Build a parent exactly once, when its first child arrives.
            // The runtime can also preserve unknown siblings here.
            current["properties"][part] =
                json!({"type": "object", "properties": {}, "additionalProperties": true});
        }
        current = &mut current["properties"][part];
    }
}

